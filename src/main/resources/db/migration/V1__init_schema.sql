CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(64) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(32) NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku VARCHAR(64) NOT NULL UNIQUE,
    name VARCHAR(255) NOT NULL,
    category VARCHAR(120) NOT NULL,
    uom VARCHAR(32) NOT NULL,
    tracking_type VARCHAR(16) NOT NULL,
    average_cost NUMERIC(14, 4) NOT NULL DEFAULT 0,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_products_avg_cost CHECK (average_cost >= 0)
);

CREATE TABLE warehouses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(32) NOT NULL UNIQUE,
    name VARCHAR(255) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE storage_locations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    warehouse_id BIGINT NOT NULL REFERENCES warehouses (id),
    zone VARCHAR(32) NOT NULL,
    aisle VARCHAR(32) NOT NULL,
    rack VARCHAR(32) NOT NULL,
    bin VARCHAR(32) NOT NULL,
    code VARCHAR(128) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_location_warehouse_code UNIQUE (warehouse_id, code)
);

CREATE TABLE inventory_balances (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES products (id),
    location_id BIGINT NOT NULL REFERENCES storage_locations (id),
    lot_number VARCHAR(64) NOT NULL DEFAULT '',
    expiry_date DATE,
    physical_qty NUMERIC(14, 4) NOT NULL DEFAULT 0,
    committed_qty NUMERIC(14, 4) NOT NULL DEFAULT 0,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_balance_prod_loc_lot UNIQUE (product_id, location_id, lot_number),
    CONSTRAINT chk_balance_physical_non_neg CHECK (physical_qty >= 0),
    CONSTRAINT chk_balance_committed_valid CHECK (committed_qty >= 0 AND committed_qty <= physical_qty)
);

CREATE INDEX idx_balances_fefo ON inventory_balances (product_id, expiry_date, id);

CREATE TABLE serial_numbers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES products (id),
    serial_code VARCHAR(128) NOT NULL UNIQUE,
    location_id BIGINT REFERENCES storage_locations (id),
    lot_number VARCHAR(64) NOT NULL DEFAULT '',
    status VARCHAR(24) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE inventory_movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES products (id),
    warehouse_id BIGINT NOT NULL REFERENCES warehouses (id),
    location_id BIGINT NOT NULL REFERENCES storage_locations (id),
    movement_type VARCHAR(24) NOT NULL,
    quantity NUMERIC(14, 4) NOT NULL,
    unit_cost NUMERIC(14, 4) NOT NULL DEFAULT 0,
    lot_number VARCHAR(64) NOT NULL DEFAULT '',
    serial_code VARCHAR(128),
    reference_doc VARCHAR(128),
    reason VARCHAR(255),
    operator_username VARCHAR(64) NOT NULL,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_movements_product_time ON inventory_movements (product_id, occurred_at DESC);
CREATE INDEX idx_movements_warehouse_time ON inventory_movements (warehouse_id, occurred_at DESC);
CREATE INDEX idx_movements_lot ON inventory_movements (lot_number);
CREATE INDEX idx_movements_serial ON inventory_movements (serial_code);

CREATE TABLE transfer_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transfer_number VARCHAR(64) NOT NULL UNIQUE,
    source_warehouse_id BIGINT NOT NULL REFERENCES warehouses (id),
    dest_warehouse_id BIGINT NOT NULL REFERENCES warehouses (id),
    status VARCHAR(24) NOT NULL,
    created_by VARCHAR(64) NOT NULL,
    shipped_at TIMESTAMP WITH TIME ZONE,
    received_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE transfer_order_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transfer_order_id BIGINT NOT NULL REFERENCES transfer_orders (id),
    product_id BIGINT NOT NULL REFERENCES products (id),
    source_location_id BIGINT NOT NULL REFERENCES storage_locations (id),
    dest_location_id BIGINT NOT NULL REFERENCES storage_locations (id),
    lot_number VARCHAR(64) NOT NULL DEFAULT '',
    serial_code VARCHAR(128),
    quantity NUMERIC(14, 4) NOT NULL,
    CONSTRAINT chk_transfer_line_qty CHECK (quantity > 0)
);
